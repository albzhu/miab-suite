def cmd_sweep(args):
    """Safety net: find pending callbacks older than N minutes (orphans)."""
    # Rotate ledger if it has grown too large
    rotated = rotate_ledger_if_needed()
    cutoff = _dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(minutes=args.older_than)
    stale = []
    quarantined = 0
    for p in sorted(cb_dir().glob("cb-*.json")):
        try:
            e = json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            quarantine_envelope(p, f"{type(exc).__name__}: {exc}")
            quarantined += 1
            continue
        if e.get("status") != "pending":
            continue
        # Internal id-vs-filename consistency check, defence in depth: don't let
        # envelope_path()'s strict validate_id() (T1) abort the whole sweep loop
        # over one tampered/legacy envelope — quarantine just that one instead.
        if not isinstance(e.get("id"), str) or e["id"] != p.stem or not ID_RE.match(e["id"]):
            quarantine_envelope(p, "id field missing, mismatched, or invalid")
            quarantined += 1
            continue
        try:
            updated = _dt.datetime.strptime(e["updatedAt"], "%Y-%m-%dT%H:%M:%SZ").replace(
                tzinfo=_dt.timezone.utc)
        except (KeyError, ValueError) as exc:
            quarantine_envelope(p, f"bad updatedAt: {exc}")
            quarantined += 1
            continue
        if updated < cutoff:
            stale.append(e)
            if args.fail:
                e["status"] = "failed"
                e["history"].append({"at": now_iso(), "agent": "sweep", "action": "fail",
                                     "detail": f"stale > {args.older_than}m"})
                ledger_append({"id": e["id"], "event": "fail", "by": "sweep",
                               "reason": f"stale>{args.older_than}m", "holder": e.get("holder")})
                _purge(e["id"], e)
    emit({"ok": True, "stale_count": len(stale), "failed": bool(args.fail),
          "ledger_rotated": rotated, "quarantined": quarantined,
          "stale": [{"id": e["id"], "holder": e.get("holder"), "task": e.get("task"),
                     "updatedAt": e["updatedAt"]} for e in stale]})


