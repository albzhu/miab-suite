#!/usr/bin/env python3
"""
claw-callback — file-based callback/continuation registry for the OpenClaw agent ensemble.

Lets a delegating agent yield instead of blocking: it packages a compact "resume"
context (what to do when woken), fires the delegation, and ends its turn. The
finishing agent wakes the next agent in the return stack via the agent-to-agent
message tool, forwarding the whole envelope so prior callbacks travel with the work.

State: one JSON envelope per callback in <root>/state/callbacks/, plus an append-only
ledger.jsonl. Completed envelopes are deleted (cleanup-on-completion); a one-line
summary is kept in the ledger for audit.

Model: a LIFO return stack. Each frame is an agent waiting to be resumed, with the
compact context it needs. Delegating pushes a frame; finishing pops the top frame and
wakes that agent. See CALLBACKS.md for the full protocol.

Subcommands:
  create   originator delegates work, registers a callback         (push origin frame)
  forward  a holder delegates further, packaging prior callbacks   (push another frame)
  return   the current holder finishes, wakes the next agent       (pop top frame)
  resolve  the origin completes the whole task; clean up           (delete + ledger)
  show     print one envelope
  list     list active envelopes
  sweep    find/fail stale orphaned callbacks (safety net)

All mutating subcommands print a JSON object to stdout for the agent to act on.
"""

import argparse
import datetime as _dt
import functools
import json
import os
import re
import secrets
import stat
import sys
from pathlib import Path
from typing import Optional

VERSION = "2.0.0"   # string semver, matching CHANGELOG.md — not a float

# Script identity, used to make every emitted command copy-pasteable from any cwd. (T2)
SELF = Path(__file__).resolve()


def self_cmd(rest: str) -> str:
    return f"python3 {SELF} {rest}"


# Callback ids are always generated by new_id(): "cb-" + 14-digit UTC timestamp +
# 6 hex chars. Anything else is either a mistake or an attempted path-traversal
# payload arriving via agent-generated `callback://<id>` text. (T1 / S0)
ID_RE = re.compile(r"^cb-\d{14}-[0-9a-f]{6}$")

# Routing agentIds are opaque to us, but every one the reference deployment uses has
# the form `agent:<slug>`. A bare `planner` (no prefix) is almost always a paste of a
# logical name into the wrong flag, and it routes to nothing. We warn rather than
# refuse: existing registries contain such entries and refusing would strand them. (T14)
AGENT_ID_RE = re.compile(r"^agent:[a-z0-9_-]+$")

# A delegation chain deeper than this is a runaway, not a plan. (T12)
MAX_STACK_DEPTH = 8


def canon(name) -> str:
    """Canonical form of a logical agent name.

    The registry was exact-match and case-sensitive, so `ECHO`, `echo` and `Echo`
    were three different agents — one registered, two silent misses that fell to
    the unregistered-agent path. Canonicalise on the way in and on the way out. (T14)
    """
    return str(name or "").strip().casefold()


# --------------------------------------------------------------------------- paths
def _validate_root(root: Path) -> None:
    """Refuse to run against a CLAW_HOME we don't trust. (T4 / S8)

    A poisoned $CLAW_HOME env var can redirect state onto an attacker-controlled
    tree, including agent-registry.json which decides where wake events route.
    If the root doesn't exist yet, this is a first run; cb_dir()'s mkdir(parents=True)
    will create it under the process umask (see T5), so there's nothing to validate.

    The mode check is a bitmask test, not a numeric one: any group-or-other bit
    (0o077) being set is refused, regardless of what the owner triad is. A plain
    `mode > 0o700` comparison is wrong here — e.g. 0o550 and 0o505 are both
    numerically <= 0o700 but are group- or world-readable.
    """
    if not root.exists():
        return
    st = root.stat()
    if st.st_uid != os.geteuid():
        die(f"CLAW_HOME root {root} is owned by uid {st.st_uid}, not the current "
            f"user (uid {os.geteuid()}); refusing to run")
    mode = stat.S_IMODE(st.st_mode)
    if mode & 0o077:
        die(f"CLAW_HOME root {root} has mode {oct(mode)} (must not be group- or "
            f"world-accessible); refusing to run")


@functools.lru_cache(maxsize=1)
def root_dir() -> Path:
    """Resolve the .openclaw root. CLAW_HOME wins, else standard default ~/.openclaw."""
    env = os.environ.get("CLAW_HOME")
    root = (Path(env).expanduser() if env else Path("~/.openclaw").expanduser()).resolve()
    _validate_root(root)
    return root


def cb_dir() -> Path:
    d = root_dir() / "state" / "callbacks"
    d.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(d, 0o700)   # T5 / S2: defence in depth beyond umask for pre-existing dirs
    except OSError:
        pass
    return d


def ledger_path() -> Path:
    return cb_dir() / "ledger.jsonl"


def registry_path() -> Path:
    return cb_dir() / "agent-registry.json"


def load_registry() -> dict:
    """Load agent registry; return empty structure if missing."""
    p = registry_path()
    if not p.exists():
        return {"version": 1, "agents": {}}
    try:
        return json.loads(p.read_text())
    except (json.JSONDecodeError, OSError):
        return {"version": 1, "agents": {}}


def save_registry(reg: dict) -> None:
    reg["updatedAt"] = now_iso()
    p = registry_path()
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(reg, indent=2, ensure_ascii=False))
    os.chmod(tmp, 0o600)   # T5 / S2
    tmp.replace(p)


def registry_index(reg: Optional[dict] = None) -> dict:
    """Map every canonical name — registry key or alias — to (key, entry). (T14)

    Exact keys win over aliases, so an agent registered under its own name is never
    shadowed by another agent claiming it as an alias.
    """
    reg = reg if reg is not None else load_registry()
    agents = reg.get("agents", {})
    idx = {}
    for key, entry in agents.items():
        for a in entry.get("aliases", []):
            idx.setdefault(canon(a), (key, entry))
    for key, entry in agents.items():
        idx[canon(key)] = (key, entry)       # exact keys overwrite alias claims
    return idx


def resolve_agent(logical_name: str, reg: Optional[dict] = None):
    """(canonical_key, entry) for a name given in any registered spelling, or (None, None)."""
    hit = registry_index(reg).get(canon(logical_name))
    return hit if hit else (None, None)


def lookup_agent(logical_name: str) -> Optional[dict]:
    """Return the registry entry for a logical agent name, or None if not found."""
    return resolve_agent(logical_name)[1]


def agent_key(name) -> str:
    """The name to *record* on an envelope for `name`. (T14)

    Registry-aware, unlike bare canon(): an agent addressed by an alias must be
    recorded under its canonical registry key, or the envelope says `echo` while the
    agent identifies as `reviewer` and every later authority check refuses it — the
    exact failure T15 exists to prevent, reintroduced by the alias feature.

    Falls back to the plain canonical form for agents nobody has registered.
    """
    key, _ = resolve_agent(name)
    return key or canon(name)


def display_name(logical_name: str, reg: Optional[dict] = None) -> str:
    """Human-facing name for an agent: registry displayName, else the canonical key,
    else whatever we were given. Read by the miab-observer observer. (T14 / Q9)"""
    key, entry = resolve_agent(logical_name, reg)
    if entry and entry.get("displayName"):
        return entry["displayName"]
    return key or str(logical_name)


def wake_route(entry: dict) -> str:
    """Emit the exact wake instruction for a registry entry (sessionKey preferred)."""
    sk = entry.get("sessionKey")
    if sk:
        return (f"Send the wake/resume to the target session with: sessions_send(sessionKey='{sk}', "
                f"message=<dispatch_message above>). Then END YOUR TURN.")
    return (f"Call the cron tool with: action=wake, agentId='{entry['agentId']}', "
            f"text=<dispatch_message above>. Then END YOUR TURN.")


def require_authority(env: dict, actor: str, expected: str, role: str,
                      action: str, force: bool) -> bool:
    """Enforce that `actor` is the agent entitled to take `action` on this bottle. (T15)

    Returns True when the check was overridden with --force, so the caller can record
    an `authority-override` ledger event. Refuses (fail-closed, non-zero) otherwise.

    Comparison is on canonical names (T14): an agent that returns as `ECHO` when the
    envelope recorded `reviewer` is the same agent, and rejecting it would be a
    regression rather than a control.
    """
    if agent_key(actor) == agent_key(expected):
        return False
    if force:
        return True
    die(f"{action} refused: --from '{actor}' is not the {role} of {env['id']} "
        f"(that is '{expected}'). If this is deliberate, re-run with --force; the "
        f"override is recorded in the ledger.")


def validate_id(cid: str) -> str:
    """Reject anything that isn't a callback id we could have generated ourselves.
    Ids arrive from agent-generated `callback://<id>` text, so this is reachable
    by prompt injection into any agent that can call the broker. (T1 / S0)"""
    if not ID_RE.match(cid):
        die(f"invalid callback id: {cid!r}")
    return cid


def envelope_path(cid: str) -> Path:
    validate_id(cid)
    p = (cb_dir() / f"{cid}.json").resolve()
    if p.parent != cb_dir().resolve():   # defence in depth
        die("path escapes callback root")
    return p


def archive_dir(subdir: str = "") -> Path:
    d = (cb_dir() / "archive" / subdir) if subdir else (cb_dir() / "archive")
    d.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(d, 0o700)   # T5 / S2
    except OSError:
        pass
    return d


def archive_path(cid: str, subdir: str = "") -> Path:
    """Same containment guarantee as envelope_path(), for archive/ writes. (T1 / S0)"""
    validate_id(cid)
    d = archive_dir(subdir).resolve()
    p = (d / f"{cid}.json").resolve()
    if p.parent != d:
        die("path escapes archive root")
    return p


def quarantine_envelope(p: Path, reason: str) -> None:
    """Move an unparseable/inconsistent envelope out of the hot dir instead of
    silently skipping it, so it's visible to both the operator and the next
    sweep instead of becoming an immortal zombie. Best-effort: a diagnostics
    path must never itself raise. (T6 / S7)"""
    try:
        dest_dir = archive_dir("corrupt")
        dest = dest_dir / p.name
        p.replace(dest)
        ledger_append({"id": p.stem, "event": "corrupt", "by": "system",
                       "reason": reason, "quarantined_to": str(dest)})
    except OSError:
        pass


# --------------------------------------------------------------------------- helpers
def now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def new_id() -> str:
    stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%d%H%M%S")
    suffix = secrets.token_hex(3)   # 3 bytes = 6 hex chars, cryptographically random
    return f"cb-{stamp}-{suffix}"


def load(cid: str) -> dict:
    p = envelope_path(cid)
    if not p.exists():
        die(f"no such callback: {cid} (looked in {p})")
    return json.loads(p.read_text())


def save(env: dict) -> Path:
    """Atomic write."""
    env["updatedAt"] = now_iso()
    p = envelope_path(env["id"])
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(env, indent=2, ensure_ascii=False))
    os.chmod(tmp, 0o600)   # T5 / S2
    tmp.replace(p)
    return p


def ledger_append(record: dict) -> None:
    record = {"at": now_iso(), **record}
    lp = ledger_path()
    with lp.open("a") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")
    try:
        os.chmod(lp, 0o600)   # T5 / S2
    except OSError:
        pass


def rotate_ledger_if_needed(max_lines: int = 10_000) -> bool:
    """Rotate ledger.jsonl if it exceeds max_lines. Returns True if rotated."""
    p = ledger_path()
    if not p.exists():
        return False
    try:
        # O(n) scan; acceptable since sweep is infrequent and max_lines bounds the cost
        text = p.read_text(encoding="utf-8")
    except OSError:
        return False
    line_count = sum(1 for line in text.splitlines() if line.strip())
    if line_count < max_lines:
        return False
    stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%d%H%M%S")
    archive = p.with_name(f"ledger.{stamp}.jsonl")
    # Handle same-second double-sweep collision
    n = 1
    while archive.exists():
        archive = p.with_name(f"ledger.{stamp}.{n}.jsonl")
        n += 1
    try:
        p.rename(archive)
    except OSError:
        return False
    return True


def emit(obj: dict) -> None:
    """Machine-readable result for the calling agent."""
    print(json.dumps(obj, indent=2, ensure_ascii=False))


def _purge(cid: str, env: dict) -> bool:
    """Delete a finished envelope. If the FS blocks unlink, mark it resolved in
    place so it never lingers as 'pending'. Returns True if the file was removed."""
    p = envelope_path(cid)
    try:
        p.unlink(missing_ok=True)
        return True
    except OSError:
        env["status"] = env.get("status", "resolved")
        try:
            save(env)
        except OSError:
            pass
        return False


def die(msg: str, code: int = 1):
    print(json.dumps({"ok": False, "error": msg}), file=sys.stderr)
    sys.exit(code)


MAX_RESUME_BYTES = 64 * 1024
RESUME_ALLOWED_KEYS = {"summary", "steps", "expects", "integrate"}


def validate_resume_shape(resume) -> dict:
    """Schema-validate a resume object arriving from --resume-json/--resume-file —
    both are untrusted input that lands verbatim in the dispatch_message sent to
    another agent. (T7 / S3)"""
    if not isinstance(resume, dict):
        die("resume context must be a JSON object")
    extra = set(resume.keys()) - RESUME_ALLOWED_KEYS
    if extra:
        die(f"resume context has unknown keys: {sorted(extra)}")
    if "summary" in resume and not isinstance(resume["summary"], str):
        die("resume.summary must be a string")
    if "steps" in resume and not (isinstance(resume["steps"], list)
                                   and all(isinstance(s, str) for s in resume["steps"])):
        die("resume.steps must be a list of strings")
    if "expects" in resume and not isinstance(resume["expects"], str):
        die("resume.expects must be a string")
    if "integrate" in resume and not isinstance(resume["integrate"], str):
        die("resume.integrate must be a string")
    return resume


def build_resume(args) -> dict:
    """Assemble the compact continuation context from flags / json / file."""
    if getattr(args, "resume_file", None):
        fp = Path(args.resume_file).expanduser().resolve()
        if not getattr(args, "allow_outside", False):
            root = root_dir().resolve()
            try:
                fp.relative_to(root)
            except ValueError:
                die(f"--resume-file {fp} is outside CLAW_HOME ({root}); "
                    f"pass --allow-outside to permit reading it")
        try:
            size = fp.stat().st_size
        except OSError as e:
            die(f"cannot read --resume-file {fp}: {e}")
        if size > MAX_RESUME_BYTES:
            die(f"--resume-file {fp} is {size} bytes, exceeds the {MAX_RESUME_BYTES}-byte limit")
        return validate_resume_shape(json.loads(fp.read_text()))
    if getattr(args, "resume_json", None):
        return validate_resume_shape(json.loads(args.resume_json))
    resume = {}
    if args.summary:
        resume["summary"] = args.summary
    if args.step:
        resume["steps"] = list(args.step)
    if args.expects:
        resume["expects"] = args.expects
    if args.integrate:
        resume["integrate"] = args.integrate
    if not resume:
        die("a resume context is required: use --summary/--step/--expects/--integrate, "
            "or --resume-json, or --resume-file")
    return resume


def wake_message(cid: str, target: str, resume: dict, results: list, terminal: bool) -> str:
    """The exact text the finishing agent should send to `target` via agent-to-agent."""
    last = results[-1] if results else None
    lines = [
        f"RESUME callback://{cid}",
        f"You were waiting on delegated work; it's back. Reload your context with:",
        f"  {self_cmd(f'show --id {cid}')}",
        "",
        "Your resume context:",
        f"  summary : {resume.get('summary','-')}",
    ]
    steps = resume.get("steps") or []
    if steps:
        lines.append("  steps   :")
        lines += [f"    {i+1}. {s}" for i, s in enumerate(steps)]
    if resume.get("expects"):
        lines.append(f"  expects : {resume['expects']}")
    if resume.get("integrate"):
        lines.append(f"  integrate: {resume['integrate']}")
    if last:
        lines += ["", f"Latest result from {last['from']}:", f"  {last['result']}"]
        if last.get("artifacts"):
            lines.append(f"  artifacts: {', '.join(last['artifacts'])}")
    if terminal:
        lines += ["", "This is the ORIGIN frame — finish the overall task, then run:",
                  f"  {self_cmd(f'resolve --id {cid} --from {target}')}"]
    else:
        lines += ["", "When you finish your part, hand back with `return` (or `forward` to delegate again)."]
    return "\n".join(lines)


# --------------------------------------------------------------------------- commands
def cmd_register(args):
    """Register or update an agent's routing info in the registry. (T14)"""
    reg = load_registry()
    agents = reg.setdefault("agents", {})
    key = canon(args.agent)
    warnings = []

    # Migrate a differently-cased duplicate of this agent onto the canonical key
    # rather than leaving two entries to drift apart.
    for existing in [k for k in agents if k != key and canon(k) == key]:
        merged = agents.pop(existing)
        merged.update(agents.get(key, {}))
        agents[key] = merged
        warnings.append(f"merged duplicate registry entry '{existing}' into '{key}'")

    entry = agents.get(key, {})
    entry["agentId"] = args.agent_id
    if not AGENT_ID_RE.match(args.agent_id):
        warnings.append(
            f"agentId '{args.agent_id}' does not look like a routing id (expected "
            f"'agent:<slug>'). Wakes for '{key}' will be dispatched to it verbatim and "
            f"will silently go nowhere if it is not a real routing id.")
    if args.session_key:
        entry["sessionKey"] = args.session_key
    if args.display_name:
        entry["displayName"] = args.display_name
    if args.description:
        entry["description"] = args.description

    if args.alias:
        idx = registry_index(reg)
        aliases = list(entry.get("aliases", []))
        for raw in args.alias:
            a = canon(raw)
            if not a:
                continue
            if a == key or a in {canon(x) for x in aliases}:
                continue
            # Compare canonically: a legacy registry holds the key `ECHO`, and the
            # alias being added is `echo`. Those are the same entry.
            dup_key = next((k for k in agents if canon(k) == a), None)
            if dup_key is not None:
                # A duplicate entry pointing at the same routing id is the thing an
                # alias is meant to replace — absorb it. Anything else is a genuine
                # collision between two agents and stays refused. (T14 migration)
                dup = agents[dup_key]
                if dup.get("agentId") != entry["agentId"]:
                    die(f"alias '{raw}' is already a registered agent, and its agentId "
                        f"({dup.get('agentId')!r}) differs from '{key}'s ({entry['agentId']!r}). "
                        f"If they are the same agent, re-register '{raw}' with the correct "
                        f"agentId first; if they are not, pick a different alias.")
                agents.pop(dup_key)
                for field in ("sessionKey", "displayName", "description"):
                    if field in dup and field not in entry:
                        entry[field] = dup[field]
                for inherited in dup.get("aliases", []):
                    if canon(inherited) not in {canon(x) for x in aliases} and canon(inherited) != key:
                        aliases.append(canon(inherited))
                warnings.append(
                    f"absorbed duplicate agent '{raw}' (same agentId "
                    f"{entry['agentId']}) into '{key}' as an alias")
                aliases.append(a)
                idx = registry_index(reg)   # the absorbed entry is gone; re-index
                continue
            owner = idx.get(a)
            if owner and canon(owner[0]) != key:
                die(f"alias '{raw}' already resolves to agent '{owner[0]}'; "
                    f"refusing to point one name at two agents")
            aliases.append(a)
        entry["aliases"] = aliases

    entry["updatedAt"] = now_iso()
    agents[key] = entry
    save_registry(reg)

    route = (f"sessions_send(sessionKey='{args.session_key}')" if args.session_key
             else f"cron(action=wake, agentId='{args.agent_id}')")
    known = ", ".join([key] + list(entry.get("aliases", [])))
    emit({
        "ok": True,
        "agent": key,
        "agentId": args.agent_id,
        **({"aliases": entry["aliases"]} if entry.get("aliases") else {}),
        **({"displayName": entry["displayName"]} if entry.get("displayName") else {}),
        **({"sessionKey": args.session_key} if args.session_key else {}),
        **({"warnings": warnings} if warnings else {}),
        "next_step": (f"Agent '{key}' registered with agentId '{args.agent_id}'"
                      + (f" and sessionKey '{args.session_key}'" if args.session_key else "") + ". "
                      f"Recognised names (case-insensitive): {known}. "
                      f"Future `return` and `wake` calls targeting this agent will use {route}."),
    })


def cmd_wake(args):
    """Look up the target agent and emit the exact cron call to wake them."""
    env = load(args.id)

    # Determine target: either --to override, or the current holder
    target_name = args.to or env.get("holder")
    if not target_name:
        die(f"Cannot determine wake target: no --to and no holder in envelope {args.id}")

    resolved_name, entry = resolve_agent(target_name)

    # Build the dispatch message (either from envelope's active frame or a fresh prompt)
    active = env.get("active")
    results = env.get("results", [])

    if active:
        terminal = len(env.get("stack", [])) == 0
        msg = wake_message(args.id, target_name, active["resume"], results, terminal)
    else:
        # No active frame yet: this is a delegation (create/forward), not a resume.
        # Emit a new-task assignment carrying the callback ref + the task text, matching
        # the inline next_step that `create` prints.
        msg = (f"[New Task] callback://{args.id} - {env.get('task', '(no task description)')}\n"
               f"You have been delegated work. Load full context with:\n"
               f"  {self_cmd(f'show --id {args.id}')}\n"
               f"When done, `return` (or `forward` to delegate further) — pass callback://{args.id} along.")

    if entry:
        agent_id = entry["agentId"]
        session_key = entry.get("sessionKey")
        emit({
            "ok": True,
            "id": args.id,
            "wake_agent": resolved_name or target_name,
            **({"requested_agent": target_name} if canon(target_name) != canon(resolved_name or target_name) else {}),
            "agentId": agent_id,
            **({"sessionKey": session_key} if session_key else {}),
            "dispatch_message": msg,
            "next_step": wake_route(entry),
        })
    else:
        # Registry miss -- emit fallback instructions
        emit({
            "ok": False,
            "id": args.id,
            "wake_agent": target_name,
            "agentId": None,
            "dispatch_message": msg,
            "registry_miss": True,
            "next_step": (
                f"Agent '{target_name}' is not in the registry "
                f"({registry_path()}). "
                f"Either: (a) register them first with "
                f"`{self_cmd(f'register --agent {target_name} --agent-id <their agentId>')}`, "
                f"then retry `wake`, OR (b) manually call "
                f"cron(action=wake, agentId=<their agentId>, text=<dispatch_message above>). "
                f"The dispatch_message is ready above."
            ),
        })
        sys.exit(1)   # T6 / S7: ok:false must never exit 0 — no wrapper could detect this failure


def cmd_create(args):
    resume = build_resume(args)
    cid = new_id()
    env = {
        "id": cid,
        "version": VERSION,
        "status": "pending",
        "task": args.task,
        "createdBy": agent_key(args.frm),
        "holder": agent_key(args.to),
        "createdAt": now_iso(),
        "updatedAt": now_iso(),
        "stack": [{"agent": agent_key(args.frm), "resume": resume, "pushedAt": now_iso()}],
        "active": None,
        "results": [],
        "history": [{"at": now_iso(), "agent": args.frm, "action": "create",
                     "detail": f"delegate -> {args.to}"}],
    }
    save(env)
    ledger_append({"id": cid, "event": "create", "by": args.frm, "to": args.to, "task": args.task})
    emit({
        "ok": True, "id": cid, "ref": f"callback://{cid}", "file": str(envelope_path(cid)),
        "holder": args.to, "stack_depth": 1,
        "next_step": (
            f"Dispatch the task to '{args.to}' by calling: "
            f"cron(action=wake, agentId=<{args.to}'s agentId from registry>, "
            f"text='[New Task] callback://{cid} - {args.task}'). "
            f"Or use `{self_cmd(f'wake --id {cid} --to {args.to}')}` "
            f"to get the exact call. Then END YOUR TURN."
        ),
    })


def cmd_forward(args):
    env = load(args.id)
    if env["status"] != "pending":
        die(f"callback {args.id} is {env['status']}, cannot forward")
    prior_holder = env["holder"]
    overridden = require_authority(env, args.frm, prior_holder, "current holder",
                                   "forward", args.force)

    # T12 — a chain deeper than MAX_STACK_DEPTH, or one that hands work back to an
    # agent already waiting on it, is a runaway rather than a plan. Production has
    # logged a self-forward; nothing complained and the envelope grew unbounded.
    depth = len(env.get("stack", []))
    if depth >= MAX_STACK_DEPTH and not args.allow_cycle:
        die(f"forward refused: callback {args.id} already has {depth} frames on the "
            f"stack (MAX_STACK_DEPTH={MAX_STACK_DEPTH}). This is almost always a "
            f"delegation loop. Pass --allow-cycle to override.")
    waiting = [agent_key(f["agent"]) for f in env.get("stack", [])]
    if not args.allow_cycle:
        if agent_key(args.to) == agent_key(args.frm):
            die(f"forward refused: '{args.frm}' cannot forward to itself. "
                f"Pass --allow-cycle if this is deliberate.")
        if agent_key(args.to) in waiting:
            die(f"forward refused: '{args.to}' is already waiting on this callback "
                f"(stack: {', '.join(waiting)}); forwarding to them would deadlock the "
                f"chain. Pass --allow-cycle to override.")

    resume = build_resume(args)
    env["stack"].append({"agent": agent_key(args.frm), "resume": resume, "pushedAt": now_iso()})
    env["holder"] = agent_key(args.to)
    env["history"].append({"at": now_iso(), "agent": args.frm, "action": "forward",
                           "detail": f"delegate -> {args.to}"})
    save(env)
    ledger_append({"id": args.id, "event": "forward", "by": args.frm, "to": args.to})
    if overridden:
        ledger_append({"id": args.id, "event": "authority-override", "by": args.frm,
                       "action": "forward", "expected": prior_holder})
    emit({
        "ok": True, "id": args.id, "ref": f"callback://{args.id}", "holder": args.to,
        "stack_depth": len(env["stack"]),
        "next_step": (
            f"Dispatch to '{args.to}' via cron(action=wake, agentId=<{args.to}'s agentId>, "
            f"text='[New Task] callback://{args.id} - forwarded from {args.frm}'). "
            f"Use `{self_cmd(f'wake --id {args.id} --to {args.to}')}` for the exact call. "
            f"Your callback is packaged on the stack. END YOUR TURN."
        ),
    })


def cmd_return(args):
    env = load(args.id)
    if env["status"] != "pending":
        die(f"callback {args.id} is {env['status']}, cannot return")
    prior_holder = env["holder"]
    overridden = require_authority(env, args.frm, prior_holder, "current holder",
                                   "return", args.force)
    env["results"].append({
        "from": args.frm, "result": args.result,
        "artifacts": list(args.artifact or []), "at": now_iso(),
    })
    if not env["stack"]:
        die(f"callback {args.id} has an empty stack; nothing to wake. Run resolve instead.")
    frame = env["stack"].pop()
    env["active"] = frame
    env["holder"] = agent_key(frame["agent"])
    terminal = len(env["stack"]) == 0
    env["history"].append({"at": now_iso(), "agent": args.frm, "action": "return",
                           "detail": f"wake -> {frame['agent']}" + (" (origin)" if terminal else "")})
    save(env)
    ledger_append({"id": args.id, "event": "return", "by": args.frm, "wake": frame["agent"]})
    if overridden:
        ledger_append({"id": args.id, "event": "authority-override", "by": args.frm,
                       "action": "return", "expected": prior_holder})

    # Look up wake target in registry
    entry = lookup_agent(frame["agent"])
    if entry:
        wake_instruction = wake_route(entry)
        wake_agent_id = entry["agentId"]
        wake_session_key = entry.get("sessionKey")
    else:
        wake_instruction = (
            f"Agent '{frame['agent']}' is not in the registry. "
            f"Run: {self_cmd(f'wake --id {args.id}')} "
            f"for guidance after registering them. "
            f"Or manually call cron(action=wake, agentId=<their agentId>, text=<dispatch_message>)."
        )
        wake_agent_id = None

    emit({
        "ok": True, "id": args.id, "ref": f"callback://{args.id}",
        "wake": frame["agent"], "wake_agentId": wake_agent_id, "terminal": terminal,
        **({"wake_sessionKey": wake_session_key} if entry and wake_session_key else {}),
        "resume": frame["resume"], "results_so_far": env["results"],
        "dispatch_message": wake_message(args.id, frame["agent"], frame["resume"],
                                         env["results"], terminal),
        "next_step": wake_instruction,
    })


def cmd_resolve(args):
    env = load(args.id)
    overridden = require_authority(env, args.frm, env.get("createdBy"), "originator",
                                   "resolve", args.force)
    # The originator resolves once the chain has fully unwound. A non-empty stack means
    # agents are still waiting to be woken — resolving here strands them silently. (T15)
    remaining = env.get("stack", [])
    if remaining and not args.force:
        die(f"resolve refused: callback {args.id} still has {len(remaining)} frame(s) "
            f"on the stack ({', '.join(f['agent'] for f in remaining)}) waiting to be "
            f"woken. Unwind with `return`, or `cancel` the callback. Pass --force to "
            f"resolve anyway; the override is recorded in the ledger.")
    if remaining and args.force:
        overridden = True
    if args.result:
        env["results"].append({"from": args.frm, "result": args.result,
                               "artifacts": [], "at": now_iso()})
    env["status"] = "resolved"
    env["history"].append({"at": now_iso(), "agent": args.frm, "action": "resolve"})
    ledger_append({
        "id": args.id, "event": "resolve", "by": args.frm,
        "task": env.get("task"), "hops": len(env.get("results", [])),
        "result": env["results"][-1]["result"] if env.get("results") else None,
    })
    if overridden:
        ledger_append({"id": args.id, "event": "authority-override", "by": args.frm,
                       "action": "resolve", "expected": env.get("createdBy"),
                       "stack_remaining": len(env.get("stack", []))})
    # cleanup-on-completion: delete the active envelope, keep the ledger line.
    cleaned = _purge(args.id, env)
    emit({"ok": True, "id": args.id, "status": "resolved", "cleaned_up": cleaned,
          "ledger": str(ledger_path()),
          "next_step": "Callback complete" + (" and envelope removed." if cleaned else
                       " (envelope marked resolved in place; delete blocked by filesystem).")
                       + " Report the final result to the user/channel."})


def cmd_cancel(args):
    env = load(args.id)
    if env["status"] != "pending":
        die(f"callback {args.id} is {env['status']}, cannot cancel")
    overridden = require_authority(env, args.frm, env.get("createdBy"), "originator",
                                   "cancel", args.force)
    env["status"] = "cancelled"
    env["history"].append({"at": now_iso(), "agent": args.frm, "action": "cancel",
                           "detail": args.reason or "Cancelled by user / system command"})
    
    # Save the updated status within the envelope context before move
    save(env)
    ledger_append({"id": args.id, "event": "cancel", "by": args.frm, "reason": args.reason or "no reason provided"})
    if overridden:
        ledger_append({"id": args.id, "event": "authority-override", "by": args.frm,
                       "action": "cancel", "expected": env.get("createdBy")})
    
    # Move envelope context file to state/callbacks/archive/ for retrospective analysis
    arch_path = archive_path(args.id)   # T1 / S0: same containment guarantee as the hot dir
    p = envelope_path(args.id)
    
    archived = False
    try:
        # Atomic rename to move out of hot callbacks dir into archive
        p.replace(arch_path)
        archived = True
    except OSError:
        # Fallback if moving fails: just purge to ensure safety
        _purge(args.id, env)

    emit({"ok": True, "id": args.id, "status": "cancelled", "cleaned_up": archived,
          "archived_to": str(arch_path) if archived else None,
          "next_step": f"Callback cancelled. Complete execution history archived to {arch_path}." if archived else
                       "Callback cancelled and purged (archiving failed)."})


def cmd_show(args):
    env = load(args.id)
    if args.json:
        emit(env)
        return
    print(f"callback://{env['id']}  [{env['status']}]")
    print(f"  task    : {env.get('task')}")
    print(f"  holder  : {env.get('holder')}   createdBy: {env.get('createdBy')}")
    print(f"  updated : {env.get('updatedAt')}")
    if env.get("active"):
        a = env["active"]
        print(f"  ACTIVE resume frame (agent={a['agent']}):")
        print(f"    summary : {a['resume'].get('summary','-')}")
        for i, s in enumerate(a["resume"].get("steps", [])):
            print(f"    step {i+1} : {s}")
        if a["resume"].get("expects"):
            print(f"    expects : {a['resume']['expects']}")
        if a["resume"].get("integrate"):
            print(f"    integrate: {a['resume']['integrate']}")
    print(f"  stack   : {len(env.get('stack', []))} frame(s) waiting "
          f"({', '.join(f['agent'] for f in env.get('stack', [])) or 'none'})")
    if env.get("results"):
        print("  results :")
        for r in env["results"]:
            print(f"    - {r['from']}: {r['result']}"
                  + (f"  [artifacts: {', '.join(r['artifacts'])}]" if r.get("artifacts") else ""))


def cmd_list(args):
    rows = []
    quarantined = 0
    for p in sorted(cb_dir().glob("cb-*.json")):
        try:
            e = json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            # T6 / S7: don't hide a corrupt envelope from the operator with a bare
            # `except: continue` — quarantine it so it's visible instead of an
            # immortal zombie that `list` and `sweep` both silently skip forever.
            quarantine_envelope(p, f"{type(exc).__name__}: {exc}")
            quarantined += 1
            continue
        rows.append(e)
    if args.json:
        emit({"ok": True, "count": len(rows), "quarantined": quarantined, "callbacks": rows})
        return
    if not rows:
        print("No active callbacks." + (f" ({quarantined} corrupt envelope(s) quarantined.)" if quarantined else ""))
        return
    print(f"{'ID':<28} {'STATUS':<9} {'HOLDER':<10} {'STACK':<6} TASK")
    for e in rows:
        print(f"{e['id']:<28} {e['status']:<9} {e.get('holder','-'):<10} "
              f"{len(e.get('stack', [])):<6} {(e.get('task') or '')[:48]}")
    if quarantined:
        print(f"({quarantined} corrupt envelope(s) quarantined to archive/corrupt/)")


def cmd_sweep(args):
    """Safety net: find pending callbacks older than N minutes (orphans)."""
    # Rotate ledger if it has grown too large
    rotated = rotate_ledger_if_needed()
    cutoff = _dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(minutes=args.older_than)
    stale = []
    quarantined = 0
    for p in sorted(cb_dir().glob("cb-*.json")):
        try:
            e = json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            quarantine_envelope(p, f"{type(exc).__name__}: {exc}")
            quarantined += 1
            continue
        if e.get("status") != "pending":
            continue
        # Internal id-vs-filename consistency check, defence in depth: don't let
        # envelope_path()'s strict validate_id() (T1) abort the whole sweep loop
        # over one tampered/legacy envelope — quarantine just that one instead.
        if not isinstance(e.get("id"), str) or e["id"] != p.stem or not ID_RE.match(e["id"]):
            quarantine_envelope(p, "id field missing, mismatched, or invalid")
            quarantined += 1
            continue
        try:
            updated = _dt.datetime.strptime(e["updatedAt"], "%Y-%m-%dT%H:%M:%SZ").replace(
                tzinfo=_dt.timezone.utc)
        except (KeyError, ValueError) as exc:
            quarantine_envelope(p, f"bad updatedAt: {exc}")
            quarantined += 1
            continue
        if updated < cutoff:
            stale.append(e)
            if args.fail:
                e["status"] = "failed"
                e["history"].append({"at": now_iso(), "agent": "sweep", "action": "fail",
                                     "detail": f"stale > {args.older_than}m"})
                ledger_append({"id": e["id"], "event": "fail", "by": "sweep",
                               "reason": f"stale>{args.older_than}m", "holder": e.get("holder")})
                _purge(e["id"], e)
    emit({"ok": True, "stale_count": len(stale), "failed": bool(args.fail),
          "ledger_rotated": rotated, "quarantined": quarantined,
          "stale": [{"id": e["id"], "holder": e.get("holder"), "task": e.get("task"),
                     "updatedAt": e["updatedAt"]} for e in stale]})


